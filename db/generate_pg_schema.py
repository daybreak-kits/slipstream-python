"""Generate llmapi/db/postgres_schema.sql from the SQLAlchemy metadata.

The schema file is derived, never hand written: it is rendered from the same
metadata the application creates at startup, so the two cannot drift. Run this
after changing l04_repo/orm.py:

    .venv/Scripts/python.exe llmapi/db/generate_pg_schema.py

The optional first argument is the output path (default: next to this file).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DB_DIR = Path(__file__).resolve().parent
SRC_DIR = DB_DIR.parent / "api" / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from l02_infra.db import Base  # noqa: E402
from l04_repo import orm  # noqa: F401,E402  (importing registers every table)

HEADER = """-- PostgreSQL schema for Slipstream.
--
-- GENERATED FILE: do not edit by hand. Run
--   python llmapi/db/generate_pg_schema.py
-- after changing llmapi/api/src/l04_repo/orm.py. The application also creates
-- these tables itself at startup (Base.metadata.create_all), so this file is
-- for provisioning, review and for a DBA who wants to see the DDL up front.
--
-- Conventions: every id is a TEXT primary key generated by the application
-- (no sequences, no AUTOINCREMENT); every *_ms / created_at / updated_at
-- column is a BIGINT holding Unix milliseconds; JSON payloads are TEXT
-- columns holding a UTF-8 JSON string (never PostgreSQL json/jsonb: the
-- application serialises explicitly and stays SQLite-compatible).
"""


def render_schema() -> str:
    dialect = postgresql.dialect()
    blocks: list[str] = [HEADER]
    tables = list(Base.metadata.sorted_tables)
    for table in tables:
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        # PostgreSQL reads a bare FLOAT as double precision, but the
        # idempotent ADD COLUMN migration says DOUBLE PRECISION: keep both
        # spellings identical so the two never look like different types.
        ddl = re.sub(r"\bFLOAT\b", "DOUBLE PRECISION", ddl)
        blocks.append("-- " + table.name + "\n" + ddl + ";")
        for index in sorted(table.indexes, key=lambda item: item.name or ""):
            blocks.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    blocks.append(
        "-- %d tables: %s" % (len(tables), ", ".join(table.name for table in tables))
    )
    return "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    output = Path(args[0]) if args else DB_DIR / "postgres_schema.sql"
    output.write_text(render_schema(), encoding="utf-8")
    print(f"wrote {output} ({len(Base.metadata.sorted_tables)} tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
